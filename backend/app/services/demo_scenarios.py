def inspect_demo_point(latitude: float, longitude: float) -> Dict[str, Any]:
    snapshot = build_demo_snapshot()
    zones = list(snapshot["red_zones"])
    shelters = list(snapshot["shelters"])
    if zones:
        nearest_zone = min(
            zones,
            key=lambda zone: _haversine_km(
                latitude, longitude, zone["latitude"], zone["longitude"]
            ),
        )
        zone_distance = _haversine_km(
            latitude, longitude, nearest_zone["latitude"], nearest_zone["longitude"]
        )
    else:
        nearest_zone = None
        zone_distance = 999.0

    nearest_shelter = None
    shelter_distance = None
    if shelters:
        nearest_shelter = min(
            shelters,
            key=lambda shelter: _haversine_km(
                latitude, longitude, shelter["latitude"], shelter["longitude"]
            ),
        )
        shelter_distance = _haversine_km(
            latitude,
            longitude,
            nearest_shelter["latitude"],
            nearest_shelter["longitude"],
        )

    if nearest_zone is None:
        risk_score = 18.0
        hazard_type = "LOW_RISK"
        risk_level = "LOW"
        urgency = "MEDIUM_TERM"
    else:
        decay = max(0.25, 1.0 - min(zone_distance, 25.0) / 35.0)
        risk_score = round(float(nearest_zone["risk_score"]) * decay, 2)
        hazard_type = nearest_zone["hazard_type"]
        risk_level = (
            "CRITICAL"
            if risk_score >= 85
            else "HIGH"
            if risk_score >= 65
            else "MEDIUM"
            if risk_score >= 40
            else "LOW"
        )
        urgency = (
            "IMMEDIATE"
            if risk_score >= 75
            else ("SHORT_TERM" if risk_score >= 50 else "MEDIUM_TERM")
        )

    return {
        "mode": "DEMO_SCENARIO",
        "scenario": snapshot["scenario"],
        "latitude": latitude,
        "longitude": longitude,
        "is_within_india": True,
        "risk_score": risk_score,
        "is_red_zone": risk_score >= 55,
        "risk_level": risk_level,
        "hazard_type": hazard_type,
        "urgency": urgency,
        "elevation": None,
        "slope_percentage": None,
        "precipitation_24h_mm": None,
        "precipitation_72h_mm": None,
        "soil_moisture_index": None,
        "temperature_celsius": None,
        "wind_speed_kmh": None,
        "humidity": None,
        "nearest_shelter": nearest_shelter,
        "nearest_shelter_km": round(shelter_distance, 2)
        if shelter_distance is not None
        else None,
        "red_zone_count_nearby": len(
            [
                z
                for z in zones
                if _haversine_km(latitude, longitude, z["latitude"], z["longitude"])
                <= 20.0
            ]
        ),
        "nearest_red_zone_distance_km": round(zone_distance, 2)
        if nearest_zone is not None
        else None,
        "model_version": "demo-scenario-1.0",
        "inspected_at": _now(),
        "data_sources": snapshot["data_sources"],
    }
