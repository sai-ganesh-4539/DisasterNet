def list_scenarios() -> List[Dict[str, Any]]:
    return [
        {
            "scenario_id": scenario["scenario_id"],
            "name": scenario["name"],
            "description": scenario["description"],
            "geography": scenario["geography"],
            "hazard_mix": list(scenario["hazard_mix"]),
            "bbox": dict(scenario["bbox"]),
            "is_active": scenario_id == _ACTIVE_SCENARIO_ID,
        }
        for scenario_id, scenario in SCENARIOS.items()
    ]


def get_active_scenario() -> Dict[str, Any]:
    return SCENARIOS[_ACTIVE_SCENARIO_ID]


def activate_scenario(scenario_id: str) -> Dict[str, Any]:
    global _ACTIVE_SCENARIO_ID
    if scenario_id not in SCENARIOS:
        raise KeyError(f"Unknown scenario: {scenario_id}")
    _ACTIVE_SCENARIO_ID = scenario_id
    return get_active_scenario()


def _counter(rows: List[Dict[str, Any]], key: str) -> Dict[str, int]:
    return dict(Counter(str(row.get(key) or "UNKNOWN") for row in rows))


